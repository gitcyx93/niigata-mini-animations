#!/usr/bin/env python3
"""Build the environment mix and a standalone sound-enabled Yahiko v20 page (copied from build-yahiko-v19-sound.py; reuses the v18 stems unchanged).

Requirements: Python 3 and FFmpeg/ffprobe. No network or Python packages.
Inputs are lossless, already-edited stems; baked DSP in mix.json is provenance,
not an instruction to apply that processing for a second time.
"""
from pathlib import Path
import base64
import hashlib
import json
import math
import subprocess

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'viz/autumn/audio/yahiko-v20'
STEMS = ROOT / 'viz/autumn/audio/yahiko-v18'
CONFIG = ASSETS / 'mix.json'
CONTROLLER = ROOT / 'viz/autumn/yahiko-v20-sound.js'
OUTPUT = ROOT / 'viz/autumn/yahiko-v20-sound.html'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(args):
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(result.stderr[-5000:])
    return result.stdout


def finite(value, name):
    number = float(value)
    if not math.isfinite(number):
        raise ValueError(f'{name} must be finite')
    return number


def build():
    config = json.loads(CONFIG.read_text(encoding='utf-8'))
    source = ROOT / config['visual_source']
    if digest(source) != config['visual_source_sha256']:
        raise ValueError('Visual source changed. Review timing/picture, then update mix.json deliberately.')
    duration = finite(config['duration_seconds'], 'duration')
    sr = int(config['sample_rate'])
    if duration != 24.6 or sr != 48000 or config['channels'] != 2:
        raise ValueError('This edition requires a 24.6-second, 48kHz stereo timeline.')
    length = round(duration * sr)
    tracks = [track for track in config['tracks'] if track['enabled']]
    if not tracks:
        raise ValueError('At least one enabled track is required')
    args = ['ffmpeg', '-nostdin', '-y', '-v', 'error']
    filters, stems = [], {}
    for i, track in enumerate(tracks):
        path = (STEMS / track['file']).resolve()
        if not path.is_relative_to(STEMS.resolve()) or not path.is_file():
            raise ValueError(f'Invalid stem path: {track["file"]}')
        at = finite(track['start_seconds'], 'start_seconds')
        gain = finite(track['gain_db'], 'gain_db')
        if not 0 <= at < duration:
            raise ValueError('Track start must be within the timeline')
        args += ['-i', str(path)]
        filters.append(
            f'[{i}:a]aresample={sr},asetpts=PTS-STARTPTS,volume={gain}dB,'
            f'adelay={round(at * sr)}S:all=1[a{i}]'
        )
        stems[track['file']] = digest(path)
    master_gain = finite(config['master_gain_db'], 'master_gain_db')
    filters.append(
        ''.join(f'[a{i}]' for i in range(len(tracks)))
        + f'amix=inputs={len(tracks)}:duration=longest:normalize=0,volume={master_gain}dB,'
        + f'apad=whole_len={length},atrim=end_sample={length},asetpts=PTS-STARTPTS[out]'
    )
    master = ASSETS / 'master.flac'
    run(args + ['-filter_complex', ';'.join(filters), '-map', '[out]',
                '-ar', str(sr), '-ac', '2', '-c:a', 'flac', '-compression_level', '8',
                '-sample_fmt', 's32', '-bits_per_raw_sample', '24', str(master)])
    encoded = ASSETS / 'master.m4a'
    run(['ffmpeg', '-nostdin', '-y', '-v', 'error', '-i', str(master),
         '-c:a', 'aac', '-b:a', '256k', '-movflags', '+faststart', str(encoded)])
    html = source.read_text(encoding='utf-8')
    if html.count('</body>') != 1:
        raise ValueError('Unexpected source HTML structure')
    config_json = json.dumps(config, ensure_ascii=False, indent=2).replace('</', '<\\/')
    audio_data = 'data:audio/mp4;base64,' + base64.b64encode(encoded.read_bytes()).decode('ascii')
    extra = (
        '\n<!-- Generated by viz/tools/build-yahiko-travel-sound.py. Edit the source controller/mix. -->\n'
        + '<script id="yahiko-sound-config" type="application/json">' + config_json + '</script>\n'
        + '<script id="yahiko-audio-data" type="text/plain">' + audio_data + '</script>\n'
        + '<script>\n' + CONTROLLER.read_text(encoding='utf-8') + '\n</script>\n'
    )
    # The original canvas source is a byte-identical prefix; only append sound.
    OUTPUT.write_text(html.replace('</body>', extra + '</body>'), encoding='utf-8')
    record = {
        'visual_source': config['visual_source'], 'visual_sha256': digest(source),
        'controller_sha256': digest(CONTROLLER), 'mix_config_sha256': digest(CONFIG),
        'stem_sha256': stems, 'master_sha256': digest(master),
        'generated_html_sha256': digest(OUTPUT), 'duration_seconds': duration,
        'sample_rate': sr, 'samples': length, 'music': False,
        'note': 'Mix reproduced from supplied edited FLAC stems; waveform/codec checks are not listening approval.'
    }
    (ASSETS / 'build.json').write_text(json.dumps(record, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Built {OUTPUT.relative_to(ROOT)} and master.flac/master.m4a ({length} samples).')


if __name__ == '__main__':
    build()
