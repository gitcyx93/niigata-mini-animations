#!/usr/bin/env python3
"""Build viz/autumn/yahiko-v26-sound.html: v26 visuals + the sound version Chen picked (v25 review B: ambience + leaves + chime + hot-spring water).
Audio is output/autumn/yahiko-v25-sound-review/02-B-water.m4a, unchanged (it carries the review's +6 dB listening gain)."""
import base64, hashlib, json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[2]
visual = (ROOT / 'viz/autumn/yahiko-v26.html').read_text(encoding='utf-8')
base = (ROOT / 'viz/autumn/yahiko-v25-sound.html').read_text(encoding='utf-8')
audio = ROOT / 'output/autumn/yahiko-v25-sound-review/02-B-water.m4a'
start = base.index('<!-- Generated by viz/tools/build-yahiko-travel-sound.py.'); end = base.rindex('</body>')
extra = base[start:end]
cfg_re = re.compile(r'<script id="yahiko-sound-config" type="application/json">([\s\S]*?)</script>')
cfg = json.loads(cfg_re.search(extra).group(1))
cfg['visual_source'] = 'viz/autumn/yahiko-v26.html'; cfg['visual_source_sha256'] = hashlib.sha256(visual.encode()).hexdigest()
cfg['note_v26'] = 'Audio = v25 sound review B (02-B-water.m4a), embedded unchanged, including its +6 dB review gain.'
extra = cfg_re.sub(lambda m: '<script id="yahiko-sound-config" type="application/json">' + json.dumps(cfg, ensure_ascii=False, indent=2) + '</script>', extra)
extra = re.sub(r'(<script id="yahiko-audio-data" type="text/plain">)[\s\S]*?(</script>)', lambda m: m.group(1) + 'data:audio/mp4;base64,' + base64.b64encode(audio.read_bytes()).decode() + m.group(2), extra)
extra = extra.replace('弥彦 v25', '弥彦 v26')
(ROOT / 'viz/autumn/yahiko-v26-sound.html').write_text(visual.replace('</body>', extra + '</body>'), encoding='utf-8')
print('Built viz/autumn/yahiko-v26-sound.html with audio B')
